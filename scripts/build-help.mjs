/**
 * build-help.mjs — builds the website's User Guide (promo/help.html → /help)
 * from the app's in-app Help, so there is ONE source of truth:
 *
 *   ../winamp-screen/index.html     → the guide content (the .welcome-body block)
 *   ../winamp-screen/src/style.css  → the guide's styles
 *   ../winamp-screen/public/guide/  → the screenshots (copied to promo/guide/)
 *
 *   node scripts/build-help.mjs
 *
 * Re-run after editing the app's Help, then commit promo/help.html + promo/guide/.
 * Never edit promo/help.html by hand — it is overwritten.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync, rmSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const APP = path.resolve(ROOT, process.env.APP_REPO || '../winamp-screen');
const PROMO = path.join(ROOT, 'promo');

// ── Content: the <div class="welcome-body"> block, matched by div depth ──────
const html = readFileSync(path.join(APP, 'index.html'), 'utf8');
const start = html.indexOf('<div class="welcome-body">');
if (start < 0) throw new Error('welcome-body not found in app index.html');
let depth = 0, end = -1;
const tag = /<(\/?)div\b[^>]*>/g;
tag.lastIndex = start;
for (let m; (m = tag.exec(html));) {
  depth += m[1] ? -1 : 1;
  if (depth === 0) { end = tag.lastIndex; break; }
}
if (end < 0) throw new Error('unbalanced welcome-body');
const body = html.slice(start, end)
  .replace(/<!--[\s\S]*?-->/g, '')                       // dev comments
  .replace(/ role="tab(list|panel)?"/g, '');              // page, not a tab widget

// ── Styles: every top-level rule for the guide, from the app's stylesheet ────
const css = readFileSync(path.join(APP, 'src/style.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
const rules = [];
for (let i = 0, d = 0, from = 0; i < css.length; i++) {
  if (css[i] === '{') d++;
  else if (css[i] === '}' && --d === 0) { rules.push(css.slice(from, i + 1).trim()); from = i + 1; }
}
const WANT = /welcome-(?!help-btn|modal)|guide-shot|guide-row|feature-badge|^kbd|rail-icon|rail-expand|@keyframes (welcomeFadeIn|slideDown)/;
const guideCss = rules.filter((r) => WANT.test(r.slice(0, r.indexOf('{')))).join('\n');
const rootVars = rules.find((r) => r.startsWith(':root'));

// ── Screenshots ─────────────────────────────────────────────────────────────
const guideOut = path.join(PROMO, 'guide');
rmSync(guideOut, { recursive: true, force: true });
mkdirSync(guideOut, { recursive: true });
const shots = readdirSync(path.join(APP, 'public/guide')).filter((f) => f.endsWith('.webp'));
for (const f of shots) copyFileSync(path.join(APP, 'public/guide', f), path.join(guideOut, f));

// ── Page ────────────────────────────────────────────────────────────────────
const page = `<!doctype html>
<!-- GENERATED by scripts/build-help.mjs from the app's in-app Help. Do not edit by hand. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>User Guide — DiscoCast Visualizer</title>
  <meta name="description" content="The DiscoCast Visualizer User Guide: audio sources, presets, auto-cycling, the Preset Studio, layers, the Timeline, projector output and keyboard shortcuts.">
  <link rel="icon" href="/favicon.svg" type="image/svg+xml">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=Space+Grotesk:wght@500;600;700&display=swap" rel="stylesheet">
  <style>
${rootVars}
* { box-sizing: border-box; margin: 0; padding: 0; }
html { scroll-padding-top: 76px; }
body { min-height: 100vh; background: #000; color: var(--text-primary); font-family: var(--font); -webkit-font-smoothing: antialiased; }
a { color: inherit; }
[data-web-only] { display: none !important; }   /* the site documents the desktop app */
${guideCss}

/* ── Website layout (the app shows this as a modal; here it is a page) ── */
.bar { position: sticky; top: 0; z-index: 30; display: flex; align-items: center; justify-content: space-between; gap: 16px;
  padding: 13px 22px; background: rgba(10,10,14,.85); backdrop-filter: blur(12px); border-bottom: 1px solid var(--border-subtle); }
.brand { display: flex; align-items: center; gap: 11px; font: 700 17px 'Space Grotesk', var(--font); text-decoration: none; }
.brand img { width: 28px; height: 28px; }
.bar-links { display: flex; align-items: center; gap: 6px; }
.nav-link { text-decoration: none; color: var(--text-secondary); font-weight: 600; font-size: 14px; padding: 9px 14px; border-radius: 10px; }
.nav-link:hover { color: var(--text-primary); background: var(--hover-medium); }
.btn { border-radius: 11px; padding: 10px 17px; font-weight: 600; font-size: 14px; color: #0e0e13; background: #ededf2; text-decoration: none; }
.btn:hover { background: #fff; }
.help-head { max-width: 1180px; margin: 0 auto; padding: 40px 22px 18px; }
.help-head h1 { font: 700 clamp(28px, 4.5vw, 40px)/1.15 'Space Grotesk', var(--font); margin-bottom: 8px; }
.help-head p { color: var(--text-secondary); }
.welcome-body { max-width: 1180px; margin: 0 auto 60px; padding: 0 22px; grid-template-columns: 240px 1fr; align-items: start; }
.welcome-rail { position: sticky; top: 76px; max-height: calc(100vh - 92px); border: 1px solid var(--border-subtle);
  border-radius: var(--radius-lg); background: var(--bg-elevated); }
.welcome-body > * { min-width: 0; }
.welcome-content img { max-width: 100%; height: auto; }
.welcome-content { overflow-wrap: anywhere; }
.welcome-content { overflow: visible; padding: 4px 0 0 36px; max-width: 860px; }
.welcome-content .welcome-section { font-size: 1.04rem; }
.welcome-content.search-active .welcome-section { display: block; }
.welcome-content.search-active .welcome-section.no-match { display: none; }
.welcome-content.search-active .welcome-section > :not(.welcome-feature):not(h4) { display: none; }
footer { border-top: 1px solid var(--border-subtle); padding: 30px 22px; text-align: center; color: var(--text-muted); font-size: 13.5px; }
@media (max-width: 760px) {
  .bar { padding: 11px 16px; } .nav-link { display: none; }
  .help-head { padding: 28px 16px 12px; }
  .welcome-body { grid-template-columns: 1fr; padding: 0 16px; }
  .welcome-rail { position: static; max-height: 320px; margin-bottom: 20px; }
  .welcome-content { padding: 0; }
  .guide-shot-row { grid-template-columns: 1fr; }
  .guide-shot--narrow img { max-width: 100%; }
}
  </style>
</head>
<body>
  <div class="bar">
    <a class="brand" href="/"><img src="/logo.png" alt="">DiscoCast</a>
    <div class="bar-links">
      <a class="nav-link" href="/">Home</a>
      <a class="nav-link" href="/presets">Presets</a>
      <a class="btn" href="/#download">Download</a>
    </div>
  </div>
  <header class="help-head">
    <h1>The DiscoCast Visualizer Guide</h1>
    <p>Everything you can do with the app. The same guide is inside the app: click <strong>User Guide</strong> on the start screen.</p>
  </header>
  ${body}
  <footer>DiscoCast Visualizer · <a href="/">Home</a> · <a href="/#download">Download</a> · <a href="/presets">Presets</a></footer>
  <script>
  (() => {
    const root = document.querySelector('.welcome-body');
    const content = root.querySelector('.welcome-content');
    const sections = [...root.querySelectorAll('.welcome-section')];
    const search = root.querySelector('#help-search');

    function show(name, sub, push = true) {
      if (!sections.some((s) => s.dataset.section === name)) name = 'welcome';
      root.querySelectorAll('.welcome-rail-btn').forEach((b) => b.classList.toggle('active', b.dataset.section === name));
      root.querySelectorAll('.welcome-rail-child').forEach((c) =>
        c.classList.toggle('active', c.dataset.section === name && c.dataset.subsection === sub));
      sections.forEach((s) => s.classList.toggle('active', s.dataset.section === name));
      if (push) history.replaceState(null, '', '#' + name + (sub ? '/' + sub : ''));
      const target = sub && content.querySelector('.welcome-section.active [data-subsection="' + sub + '"]');
      (target || document.querySelector('.help-head')).scrollIntoView({ block: 'start' });
    }

    root.querySelectorAll('.welcome-rail-btn').forEach((btn) => btn.addEventListener('click', () => {
      const kids = btn.dataset.expand && document.getElementById(btn.dataset.expand);
      if (kids) btn.classList.toggle('expanded', kids.classList.toggle('expanded'));
      clearSearch(); show(btn.dataset.section);
    }));
    root.querySelectorAll('.welcome-rail-child').forEach((c) => c.addEventListener('click', () => {
      clearSearch(); show(c.dataset.section, c.dataset.subsection);
    }));

    // Search: across ALL sections; shows only the matching feature blocks.
    function runSearch(q) {
      q = q.trim().toLowerCase();
      content.querySelector('.welcome-search-empty')?.remove();
      content.classList.toggle('search-active', !!q);
      let any = false;
      sections.forEach((s) => {
        let hit = false;
        s.querySelectorAll('.welcome-feature').forEach((f) => {
          const m = !!q && f.textContent.toLowerCase().includes(q);
          f.classList.toggle('search-match', m);
          f.style.display = q && !m ? 'none' : '';
          hit = hit || m;
        });
        s.classList.toggle('no-match', !!q && !hit);
        any = any || hit;
      });
      if (q && !any) {
        const d = document.createElement('div');
        d.className = 'welcome-search-empty';
        d.innerHTML = '<div class="welcome-search-empty-icon">🔍</div><p></p>';
        d.querySelector('p').textContent = 'No results for "' + q + '"';
        content.appendChild(d);
      }
    }
    function clearSearch() { if (search.value) { search.value = ''; runSearch(''); } }
    search.addEventListener('input', () => runSearch(search.value));
    search.addEventListener('keydown', (e) => { if (e.key === 'Escape') { clearSearch(); search.blur(); } });

    // Deep links: /help#output, /help#studio/palette
    const [name, sub] = decodeURIComponent(location.hash.slice(1)).split('/');
    const start = root.querySelector('.welcome-rail-btn[data-section="' + name + '"]');
    if (start?.dataset.expand) { document.getElementById(start.dataset.expand)?.classList.add('expanded'); start.classList.add('expanded'); }
    if (name) show(name, sub, false);
  })();
  </script>
</body>
</html>
`;
writeFileSync(path.join(PROMO, 'help.html'), page);
console.log(`promo/help.html written (${(page.length / 1024).toFixed(0)} KB) · ${shots.length} screenshots → promo/guide/`);
